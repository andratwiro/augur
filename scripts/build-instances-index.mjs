#!/usr/bin/env node
// build-instances-index.mjs — the LEAN agent index for the Augur instance registry.
// Parses skills/govocal-ui/govocal-instances.js and emits skills/govocal-ui/INSTANCES.md:
// one row per registered GV component (name · layer · props · line#). An agent reads
// THIS slim file to discover what exists + how to call it, then loads only the one
// renderer it needs (each lives under a `/* ── <name> ── */` banner in the registry) —
// never the whole 6k-line file or the 100KB components.md. Run: npm run index:instances.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'skills/govocal-ui/govocal-instances.js');
const OUT = path.join(ROOT, 'skills/govocal-ui/INSTANCES.md');
const src = fs.readFileSync(SRC, 'utf8');
const lines = src.split('\n');

// locate each GV.register("name", … and the body span until the next register/EOF.
// Skip comment lines — the per-renderer header comments mention GV.register("x", fn)
// and would otherwise double-count every component.
const regs = [];
lines.forEach((ln, i) => {
  const t = ln.trim();
  if (t.startsWith('*') || t.startsWith('//') || t.startsWith('/*')) return; // comment ref, not a call
  const m = /GV\.register\(\s*["']([^"']+)["']/.exec(ln);
  if (m) regs.push({ name: m[1], line: i + 1, idx: i });
});
regs.forEach((r, k) => { r.end = k + 1 < regs.length ? regs[k + 1].idx : lines.length; });

const layerOf = (name) => {
  if (fs.existsSync(path.join(ROOT, 'base', name))) return 'base';
  if (fs.existsSync(path.join(ROOT, 'components', name))) return 'component';
  return 'component·sub'; // iconbtn, bo-facetgroup, fo-linz-monitorband-event, …
};
const propsOf = (r) => {
  const body = lines.slice(r.idx, r.end).join('\n');
  const set = new Set();
  for (const m of body.matchAll(/props\.([A-Za-z_$][\w$]*)/g)) set.add(m[1]);
  return [...set].sort();
};

const rows = regs.map((r) => ({ name: r.name, layer: layerOf(r.name), line: r.line, props: propsOf(r) }))
  .sort((a, b) => (a.layer.localeCompare(b.layer) || a.name.localeCompare(b.name)));

const order = { base: 0, component: 1, 'component·sub': 2 };
rows.sort((a, b) => (order[a.layer] - order[b.layer]) || a.name.localeCompare(b.name));

let md = `# Augur instance index — \`window.GV\` registry\n\n`;
md += `> Generated by \`npm run index:instances\` from \`govocal-instances.js\`. The LEAN lookup:\n`;
md += `> find a component here, then load only its renderer (search the registry for the\n`;
md += `> \`/* ── <name> ── */\` banner) — never the whole file. **${rows.length} components.**\n\n`;
md += `**Use:** \`GV.render('<name>', props)\` → HTML string · \`GV.mount(elOrSel, '<name>', props)\` → inject + hydrate (fills \`data-gv-icon\`).\n`;
md += `Dot shorthand \`GV.<name>(props)\` exists for identifier-safe names; hyphenated names use \`GV.render('a-b', props)\`. Linked by default; detach is a Phase-4 CLI op.\n\n`;
md += `| Component | Layer | Props | Renderer (instances.js) |\n|---|---|---|---|\n`;
for (const r of rows) {
  const props = r.props.length ? r.props.map((p) => '`' + p + '`').join(' ') : '_(none)_';
  md += `| \`${r.name}\` | ${r.layer} | ${props} | L${r.line} |\n`;
}
md += `\nLayers: **base** = atoms (\`base/*\`) · **component** = composed (\`components/*\`) · **component·sub** = a secondary renderer registered alongside its parent.\n`;
fs.writeFileSync(OUT, md);
console.log(`Wrote INSTANCES.md — ${rows.length} components (${rows.filter(r=>r.layer==='base').length} base, ${rows.filter(r=>r.layer==='component').length} component, ${rows.filter(r=>r.layer==='component·sub').length} sub).`);
