/* Run the same probes against a REAL Durable Object, on a worker that exists for the
 * length of one measurement and is deleted at the end of it.
 *
 *   node test/rt-cost/probe-deployed.mjs --env-file <path-to-an-env-file>
 *
 * WHY. The local rehearsal answers everything except one question: whether the runtime a
 * customer's board actually runs on hibernates this room the way the local simulator does.
 * That question is the difference between an idle tab costing nothing and an idle tab
 * costing a room-minute a minute, which is two quotas an order of magnitude apart — so it
 * is worth one throwaway worker to answer rather than assume.
 *
 * WHAT IT WILL NOT DO. It refuses to touch a worker that already exists. The name it
 * generates carries a random suffix precisely so it cannot collide with a deployed one,
 * and the deletion runs in a finally — a failed probe still cleans up after itself.
 *
 * Credentials are read from a file named on the command line and are never printed. The
 * generated wrangler config goes to .wrangler/ (gitignored), like every other generated
 * config in this repo, so a stray `npx wrangler` cannot pick it up.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { BoardClient, sleep, PING_MS } from "./client.mjs";
import { saveResult } from "./ledger.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "../..");
const argv = process.argv.slice(2);
const opt = (n, d) => { const i = argv.indexOf("--" + n); return i >= 0 && argv[i + 1] ? argv[i + 1] : d; };

const envFile = opt("env-file", "");
if (!envFile) { console.error("need --env-file <path>; the values in it are never printed"); process.exit(2); }
const creds = {};
for (const line of readFileSync(envFile, "utf8").split("\n")) {
  const m = line.match(/^\s*(?:export\s+)?([A-Z0-9_]+)\s*=\s*(.*)$/);
  if (m) creds[m[1]] = m[2].replace(/^["']|["']$/g, "").trim();
}
const CF = {
  CLOUDFLARE_API_TOKEN: creds.CLOUDFLARE_API_TOKEN || creds.CF_API_TOKEN,
  CLOUDFLARE_ACCOUNT_ID: creds.CLOUDFLARE_ACCOUNT_ID || creds.CF_ACCOUNT_ID,
};
if (!CF.CLOUDFLARE_API_TOKEN || !CF.CLOUDFLARE_ACCOUNT_ID) {
  console.error(`${envFile} carries no CLOUDFLARE_API_TOKEN / CLOUDFLARE_ACCOUNT_ID`);
  process.exit(2);
}
const env = { ...process.env, ...CF };

const NAME = "rt-cost-probe-" + randomBytes(4).toString("hex");
const CFG = resolve(ROOT, ".wrangler/rt-cost-probe.toml");
const SECRET = randomBytes(16).toString("hex");

function run(args, opts = {}) {
  const r = spawnSync("npx", args, { cwd: ROOT, env, encoding: "utf8", ...opts });
  return { code: r.status, out: (r.stdout || "") + (r.stderr || "") };
}

mkdirSync(dirname(CFG), { recursive: true });
writeFileSync(CFG, `# GENERATED by test/rt-cost/probe-deployed.mjs — deleted with the worker.
name = "${NAME}"
main = "${resolve(HERE, "worker.js")}"
compatibility_date = "2026-07-01"
workers_dev = true

[vars]
RT_SHARED_SECRET = "${SECRET}"
INSTR_STORAGE = "1"

[[durable_objects.bindings]]
name = "ROOMS"
class_name = "MeasuredRoom"

[[migrations]]
tag = "v1"
new_sqlite_classes = ["MeasuredRoom"]
`);

// ---- the grace ladder, verified against the object's OWN wake log ----------
// measure.mjs runs the same ladder and reads the answer off the runtime's log stream.
// That stream does not exist for a deployed Durable Object — `wrangler tail` delivered
// nothing — so this reads the answer out of the object's storage instead. Same schedule,
// different witness, and it is a separate function precisely so the difference is visible
// rather than hidden behind a shared name.
const LADDER = [4, 8, 12, 16, 20, 25, 30, 45, 60, 90, 150];
async function graceProbe(httpsOrigin) {
  const path = `/rtcost/deployed-${Date.now()}`;
  const wsOrigin = httpsOrigin.replace(/^https:/, "wss:");
  // A brand-new worker answers `/` before its Durable Object namespace is reachable, and
  // the symptom is a WebSocket that fails its handshake with nothing useful attached. The
  // non-upgrade GET is here to turn that into a status code somebody can act on.
  let c = null;
  for (let i = 1; i <= 8 && !c; i++) {
    try { c = await new BoardClient(wsOrigin, path, "Probe").open(); }
    catch (e) {
      const probe = await fetch(`${httpsOrigin}/room?path=${encodeURIComponent(path)}`).catch((f) => f);
      const body = probe && probe.text ? (await probe.text()).slice(0, 200) : String(probe);
      console.log(`  socket attempt ${i} failed (${e.message}); /room answers ${probe && probe.status} ${body}`);
      await sleep(12000);
    }
  }
  if (!c) throw new Error("the deployed room never accepted a socket — nothing below would be a measurement");
  const ping = setInterval(() => c.raw("ping"), PING_MS);
  const t0 = Date.now();
  // The join seeds the board, which dirties it, which arms the 45s mirror alarm — and an
  // alarm inside a probe gap is a wake this would read as an eviction. Outlast it first.
  console.log("  settling 62s so the join's mirror alarm fires before the ladder starts");
  await sleep(62000);
  const probes = [];
  for (const gapSec of LADDER) {
    await sleep(gapSec * 1000);
    const at = Date.now();
    c.send({ t: "cursor", x: gapSec, y: 1 }); // pure relay: no storage write, so no alarm
    probes.push({ gapSec, at, idleSinceMs: at - (probes.length ? probes[probes.length - 1].at : t0 + 62000) });
    console.log(`  sent probe after ${gapSec}s of silence`);
  }
  await sleep(3000);
  clearInterval(ping);
  c.close();

  const r = await fetch(`${httpsOrigin}/wakes?path=${encodeURIComponent(path)}`);
  const { wakes } = await r.json();
  // ⚠️ The read-back itself is a request to the object, so the LAST wake in the log may be
  // this read rather than a probe. Wakes are matched to the probe whose gap they fall in;
  // anything after the final probe is dropped.
  const lastProbe = probes[probes.length - 1].at;
  for (const p of probes) p.woke = wakes.some((w) => w.at > p.at - p.idleSinceMs && w.at <= p.at + 2500);
  const firstWoke = probes.find((p) => p.woke);
  const lastResident = [...probes].reverse().find((p) => !p.woke && (!firstWoke || p.gapSec < firstWoke.gapSec));
  const out = {
    runtime: "a throwaway deployed worker, read back from the object's own wake log",
    at: new Date().toISOString(),
    scenario: "grace",
    question: "how long does the PRODUCTION runtime keep a hibernatable Durable Object resident after its last event?",
    ladderSec: LADDER,
    probes: probes.map((p) => ({ gapSec: p.gapSec, woke: p.woke })),
    wakesRecorded: wakes.length,
    wakeLog: wakes,
    wakesAfterTheLastProbe: wakes.filter((w) => w.at > lastProbe + 2500).length,
    graceLowerBoundSec: lastResident ? lastResident.gapSec : 0,
    graceUpperBoundSec: firstWoke ? firstWoke.gapSec : null,
    verdict: !wakes.length
      ? "THE WAKE LOG IS EMPTY — not even the join was recorded, so this measured the instrument"
      : firstWoke
        ? `eviction happens between ${lastResident ? lastResident.gapSec : 0}s and ${firstWoke.gapSec}s of idleness`
        : `no probe up to ${LADDER[LADDER.length - 1]}s forced a reconstruction: this runtime keeps a hibernatable object resident at least that long`,
  };
  saveResult(resolve(HERE, "results"), "grace-deployed", out);
  console.log("  " + out.verdict);
}

let deployed = false;
try {
  const list = run(["wrangler", "deploy", "--dry-run", "-c", CFG]);
  if (list.code !== 0) { console.error("bundle failed:\n" + list.out); process.exit(1); }
  console.log(`deploying throwaway worker ${NAME} …`);
  const d = run(["wrangler", "deploy", "-c", CFG]);
  if (d.code !== 0) { console.error("deploy failed:\n" + d.out); process.exit(1); }
  deployed = true;
  const m = d.out.match(/https:\/\/[a-z0-9.-]*\.workers\.dev/i);
  if (!m) { console.error("deploy printed no workers.dev URL:\n" + d.out); process.exit(1); }
  const httpsOrigin = m[0];
  console.log(`  up at ${httpsOrigin}`);
  // A brand-new worker can 1104 for its first minute of propagation.
  for (let i = 0; i < 30; i++) {
    try { const r = await fetch(httpsOrigin + "/"); if (r.ok) break; } catch (e) {}
    await new Promise((r) => setTimeout(r, 4000));
  }
  await graceProbe(httpsOrigin);
} finally {
  if (deployed) {
    console.log(`deleting ${NAME} …`);
    const del = run(["wrangler", "delete", "-c", CFG, "--force"]);
    console.log(del.code === 0 ? `  deleted ${NAME}` : `  ⚠ DELETE FAILED for ${NAME}:\n` + del.out);
  }
  try { rmSync(CFG); } catch (e) {}
}
